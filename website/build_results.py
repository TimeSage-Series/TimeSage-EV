"""Regenerate website/data/results.js from the paper's result tables.

Reads the unweighted-keypoint sequential-vs-independent results (every
keypoint weighs 1.0):

    <results>/single_vs_episode/per_tier.csv
    <results>/single_vs_episode/per_period_{qwen,gemma}.csv

Run from the repository root:

    python website/build_results.py ~/TimeSage-EV/workspace/cross_model_unweighted
"""
from __future__ import annotations

import argparse
import csv
import json
from collections import defaultdict
from datetime import date
from pathlib import Path
from statistics import mean

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "website" / "data" / "results.js"

TIERS = ("easy", "middle", "hard")
# single_vs_episode model key -> (display name, per-period CSV)
SVE_MODELS = {
    "Qwen": ("Qwen3.5-397B-A17B", "per_period_qwen.csv"),
    "Gemma": ("Gemma 4 31B", "per_period_gemma.csv"),
}


def period_curves(path: Path) -> dict:
    """Mean score at each period position (1st, 2nd, ... period of a scenario),
    over the scenarios that have a scored result there. Positions held by fewer
    than half the tier's scenarios are dropped."""
    by_scen = defaultdict(list)
    for r in csv.DictReader(path.open()):
        by_scen[(r["tier"], r["scenario"])].append(r)
    curves = {}
    for tier in TIERS:
        scens = [rows for (t, _), rows in by_scen.items() if t == tier]
        ep, single = defaultdict(list), defaultdict(list)
        for rows in scens:
            for k, r in enumerate(sorted(rows, key=lambda r: r["period"])):
                if r["cont_aggregate"]:
                    ep[k].append(float(r["cont_aggregate"]))
                if r["single_aggregate"]:
                    single[k].append(float(r["single_aggregate"]))
        keep = [k for k in sorted(ep) if len(ep[k]) >= len(scens) / 2 and len(single[k]) >= len(scens) / 2]
        curves[tier] = {
            "episode": [round(mean(ep[k]), 2) for k in keep],
            "single": [round(mean(single[k]), 2) for k in keep],
        }
    return curves


def single_vs_episode(results: Path) -> list[dict]:
    sve = results / "single_vs_episode"
    tiers = defaultdict(dict)
    for r in csv.DictReader((sve / "per_tier.csv").open()):
        mode = "episode" if r["mode"] == "continuous" else "single"
        tiers[r["model"]].setdefault(r["tier"], {})[mode] = float(r["mean_score"])
        tiers[r["model"]][r["tier"]]["n_" + mode] = int(r["n_scored"])
    return [{"model": name, "tiers": tiers[key], "curves": period_curves(sve / csv_name)}
            for key, (name, csv_name) in SVE_MODELS.items()]


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("results", type=Path, help="directory holding single_vs_episode/")
    results = ap.parse_args().results.expanduser()

    data = {
        "updated": date.today().isoformat(),
        "weighting": "unweighted",
        "single_vs_episode": single_vs_episode(results),
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "// Generated by website/build_results.py — do not edit by hand.\n"
        "window.RESULTS = " + json.dumps(data, indent=1, ensure_ascii=False) + ";\n"
    )
    print(f"wrote {len(data['single_vs_episode'])} single-vs-episode comparisons to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
