"""Regenerate website/data/scenarios.js from the scenario manifests.

Run from the repository root:

    python website/build_data.py
"""
from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MAINTAINER = ROOT / "evbench" / "maintainer"
# The released corpus (the Hugging Face dataset clone). When a scenario is in
# it, its periods come from the release rather than the maintainer manifest.
RELEASED = ROOT / "evbench" / "scenarios"
OUT = ROOT / "website" / "data" / "scenarios.js"

TIER_ORDER = {"easy": 0, "middle": 1, "hard": 2}

# Display names are the title up to its first dash; these are set by hand.
NAME_OVERRIDES = {
    "usda_cold_storage_butter_band_monthly": "USDA NASS Cold Storage: Butter",
    "usda_cold_storage_pork_band_monthly": "USDA NASS Cold Storage: Pork",
    # scenario.json has title "US": YAML read the rest after " #" as a comment.
    "bls_diesel_retail_price_band_weekly": "EIA Weekly US Diesel Retail Price band state",
    "cdc_nwss_wastewater_covid_la_county": "CDC Wastewater COVID-19, Los Angeles County",
    "bts_airline_load_factor_monthly": "BTS US Airline Load Factor",
}


def display_name(d: dict) -> str:
    return NAME_OVERRIDES.get(d["id"]) or re.split(r" -- | — ", d["title"])[0].strip()


def released_coverage(tier: str, domain: str, scenario_id: str) -> dict | None:
    inst = RELEASED / tier / domain / scenario_id / "instances"
    periods = sorted(p.name for p in inst.iterdir() if p.is_dir()) if inst.is_dir() else []
    if not periods:
        return None
    return {"first": periods[0], "last": periods[-1], "instances": len(periods)}


def main() -> None:
    scenarios = []
    for path in sorted(MAINTAINER.glob("*/*/*/scenario.json")):
        d = json.loads(path.read_text())
        cov = released_coverage(d["tier"], d["domain"], d["id"]) or d["coverage"]
        scenarios.append({
            "id": d["id"],
            "title": d["title"],
            "name": display_name(d),
            "tier": d["tier"],
            "domain": d["domain"],
            "cadence": d["cadence"],
            "publisher": d["source"]["publisher"],
            "source_name": d["source"].get("name", ""),
            "source_url": d["source"].get("url", ""),
            "first": cov["first"],
            "last": cov["last"],
            "instances": cov["instances"],
            "redistribution": d["license"].get("redistribution", ""),
        })
    scenarios.sort(key=lambda s: (TIER_ORDER[s["tier"]], s["domain"], s["id"]))

    OUT.parent.mkdir(parents=True, exist_ok=True)
    body = json.dumps(scenarios, indent=1, ensure_ascii=False)
    OUT.write_text(
        "// Generated by website/build_data.py — do not edit by hand.\n"
        f"window.SCENARIOS = {body};\n"
    )
    print(f"wrote {len(scenarios)} scenarios "
          f"({sum(s['instances'] for s in scenarios)} instances) to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
